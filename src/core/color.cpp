const PaletteColor& launchpadPalette(std::uint8_t index)
{
    return kPalette[index < 128 ? index : 0];
}

const Rgb& selectedPaletteRgb(std::uint8_t index)
{
    return launchpadPalette(index).rgb;
}

std::uint8_t nearestPaletteIndex(const Rgb& rgb)
{
    double best = 1e30;
    std::uint8_t bestIndex = 0;
    for (int i = 0; i < 128; ++i) {
        const Rgb& c = kPalette[i].rgb;
        const double dr = rgb.r - c.r;
        const double dg = rgb.g - c.g;
        const double db = rgb.b - c.b;
        const double distance = dr * dr + dg * dg + db * db;
        if (distance < best) {
            best = distance;
            bestIndex = static_cast<std::uint8_t>(i);
        }
    }
    return bestIndex;
}

Rgb snapToPalette(const Rgb& rgb)
{
    return launchpadPalette(nearestPaletteIndex(rgb)).rgb;
}

